-- Reorder recommendations produced by the analytics work (weekly moving-average forecast).
-- One forecast_run is one published set of recommendations; the newest run is the one shown.
-- The forecast and safety stock are stored as published. The order quantity shown to managers is
-- recomputed against live stock (see src/analytics/reorder.ts) so it stays correct after new movements.

CREATE TABLE forecast_runs (
  run_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  method      text NOT NULL,
  -- Last day of sales history the forecast was built from.
  as_of       date NOT NULL,
  service_z   numeric(5, 2) NOT NULL CHECK (service_z >= 0),
  cover_weeks numeric(5, 2) NOT NULL CHECK (cover_weeks > 0),
  source      text NOT NULL,
  -- Headline accuracy/simulation results published with the forecast (see the seed for the shape).
  evaluation  jsonb NOT NULL DEFAULT '{}',
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE reorder_recommendations (
  run_id                     integer NOT NULL REFERENCES forecast_runs (run_id) ON DELETE CASCADE,
  product_id                 integer NOT NULL REFERENCES products (product_id),
  forecast_next_week         numeric(14, 3) NOT NULL CHECK (forecast_next_week >= 0),
  safety_stock               numeric(14, 3) NOT NULL CHECK (safety_stock >= 0),
  -- Stock the analytics run saw, and the order it published for it.
  stock_at_run               numeric(14, 3) NOT NULL,
  suggested_order_packs      integer NOT NULL CHECK (suggested_order_packs >= 0),
  suggested_order_units      numeric(14, 3) NOT NULL CHECK (suggested_order_units >= 0),
  capped_by_shelf_life       boolean NOT NULL,
  weeks_of_cover_after_order numeric(8, 1),
  -- Backtest MASE of the method for this item (naive "same as last week" = 1.0; below 1.0 is better).
  method_mase                numeric(6, 3),
  PRIMARY KEY (run_id, product_id)
);
