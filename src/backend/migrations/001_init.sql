-- CafeStock data layer: products, suppliers and an append-only stock-movement ledger.
--
-- Design rules (see project-requirements.md, sections 1, 4 and 5):
--   * Current stock is NEVER stored. It is always SUM(stock_movements.quantity).
--   * stock_movements is append-only. Mistakes are corrected with a compensating ADJUST row.
--   * Stock can never go negative, per product or per batch, even under concurrent writers.
--   * Every unit of stock belongs to a batch, so perishability (expiry) is tracked in the ledger.
--
-- Custom SQLSTATE codes raised by the triggers below (mapped to HTTP errors by the API):
--   CS001 insufficient stock for the product      CS002 ledger is append-only
--   CS003 unknown batch for the product           CS004 insufficient stock in the batch

CREATE TABLE suppliers (
  supplier_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL UNIQUE CHECK (length(btrim(name)) > 0),
  contact_email text,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE products (
  product_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku               text NOT NULL UNIQUE CHECK (length(btrim(sku)) > 0),
  name              text NOT NULL CHECK (length(btrim(name)) > 0),
  unit              text NOT NULL CHECK (unit IN ('g', 'ml', 'unit')),
  unit_cost         numeric(10, 4) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
  shelf_life_days   integer CHECK (shelf_life_days > 0),
  storage_location  text,
  supplier_id       integer REFERENCES suppliers (supplier_id),
  lead_time_days    integer NOT NULL DEFAULT 0 CHECK (lead_time_days >= 0),
  pack_size         integer CHECK (pack_size > 0),
  pack_description  text,
  reorder_threshold numeric(14, 3) NOT NULL DEFAULT 0 CHECK (reorder_threshold >= 0),
  reorder_quantity  numeric(14, 3) NOT NULL DEFAULT 0 CHECK (reorder_quantity >= 0),
  created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE SEQUENCE batch_id_seq;

CREATE TABLE stock_movements (
  movement_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at      timestamptz NOT NULL DEFAULT now(),
  product_id       integer NOT NULL REFERENCES products (product_id),
  movement_type    text NOT NULL CHECK (movement_type IN ('RECEIVE', 'SELL', 'SPOILAGE', 'ADJUST')),
  quantity         numeric(14, 3) NOT NULL,
  batch_id         text NOT NULL CHECK (length(btrim(batch_id)) > 0),
  expiry_date      date,
  storage_location text,
  -- Provenance columns carried over from the sales dataset (see data/DATA_DICTIONARY.md).
  sale_id          text,
  caused_by_drink  text,
  sale_price       numeric(10, 2),
  payment_method   text,
  reason           text,
  source           text NOT NULL DEFAULT 'app' CHECK (source IN ('derived', 'synthetic', 'app')),

  -- RECEIVE adds stock, SELL and SPOILAGE remove it, ADJUST (stocktake) may do either.
  CONSTRAINT quantity_sign_matches_type CHECK (
    (movement_type = 'RECEIVE' AND quantity > 0)
    OR (movement_type IN ('SELL', 'SPOILAGE') AND quantity < 0)
    OR (movement_type = 'ADJUST' AND quantity <> 0)
  ),
  -- Stock cannot be received already expired.
  CONSTRAINT received_before_expiry CHECK (
    movement_type <> 'RECEIVE'
    OR expiry_date IS NULL
    OR expiry_date >= (occurred_at AT TIME ZONE 'UTC')::date
  )
);

CREATE INDEX stock_movements_product_time_idx ON stock_movements (product_id, occurred_at);
CREATE INDEX stock_movements_product_batch_idx ON stock_movements (product_id, batch_id);
-- A batch is created by exactly one RECEIVE.
CREATE UNIQUE INDEX stock_movements_one_receive_per_batch
  ON stock_movements (product_id, batch_id) WHERE movement_type = 'RECEIVE';

-- Append-only: no UPDATE or DELETE, for any client, regardless of application code.
CREATE FUNCTION forbid_ledger_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'stock_movements is append-only: % is not allowed; post a compensating ADJUST instead', TG_OP
    USING ERRCODE = 'CS002';
END;
$$;

CREATE TRIGGER stock_movements_append_only
  BEFORE UPDATE OR DELETE ON stock_movements
  FOR EACH ROW EXECUTE FUNCTION forbid_ledger_mutation();

-- Concurrency control + stock invariants, enforced inside the database so every writer is covered.
-- A movement that removes stock first locks the product row. Concurrent removals for the same
-- product therefore queue up, and each one re-reads the balance after the previous one commits,
-- so two simultaneous sales can never both spend the same stock.
CREATE FUNCTION enforce_ledger_rules() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  product_on_hand numeric;
  batch_on_hand   numeric;
BEGIN
  -- Unknown product: let the foreign key report it.
  IF NOT EXISTS (SELECT 1 FROM products WHERE product_id = NEW.product_id) THEN
    RETURN NEW;
  END IF;

  -- Anything other than the RECEIVE that created it must point at an existing batch.
  IF NEW.movement_type <> 'RECEIVE' AND NOT EXISTS (
    SELECT 1 FROM stock_movements
    WHERE product_id = NEW.product_id AND batch_id = NEW.batch_id AND movement_type = 'RECEIVE'
  ) THEN
    RAISE EXCEPTION 'Unknown batch % for product %', NEW.batch_id, NEW.product_id
      USING ERRCODE = 'CS003';
  END IF;

  IF NEW.quantity < 0 THEN
    PERFORM 1 FROM products WHERE product_id = NEW.product_id FOR UPDATE;

    SELECT COALESCE(SUM(quantity), 0) INTO product_on_hand
      FROM stock_movements WHERE product_id = NEW.product_id;
    IF product_on_hand + NEW.quantity < 0 THEN
      RAISE EXCEPTION 'Insufficient stock for product %: on hand %, requested %',
        NEW.product_id, product_on_hand, -NEW.quantity
        USING ERRCODE = 'CS001';
    END IF;

    SELECT COALESCE(SUM(quantity), 0) INTO batch_on_hand
      FROM stock_movements WHERE product_id = NEW.product_id AND batch_id = NEW.batch_id;
    IF batch_on_hand + NEW.quantity < 0 THEN
      RAISE EXCEPTION 'Insufficient stock in batch % of product %: on hand %, requested %',
        NEW.batch_id, NEW.product_id, batch_on_hand, -NEW.quantity
        USING ERRCODE = 'CS004';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER stock_movements_enforce_rules
  BEFORE INSERT ON stock_movements
  FOR EACH ROW EXECUTE FUNCTION enforce_ledger_rules();

-- Remaining quantity per batch, derived from the ledger.
CREATE VIEW batch_stock AS
SELECT
  product_id,
  batch_id,
  MAX(expiry_date)      AS expiry_date,
  MAX(storage_location) AS storage_location,
  SUM(quantity)         AS remaining
FROM stock_movements
GROUP BY product_id, batch_id;

-- Current stock per product, derived from the ledger (never written directly).
CREATE VIEW current_stock AS
SELECT
  p.product_id,
  p.sku,
  p.name,
  p.unit,
  p.storage_location,
  p.supplier_id,
  p.reorder_threshold,
  p.reorder_quantity,
  COALESCE(t.on_hand, 0)                        AS on_hand,
  COALESCE(t.on_hand, 0) < p.reorder_threshold  AS is_low,
  e.earliest_expiry,
  COALESCE(e.expired_quantity, 0)               AS expired_quantity
FROM products p
LEFT JOIN (
  SELECT product_id, SUM(quantity) AS on_hand FROM stock_movements GROUP BY product_id
) t ON t.product_id = p.product_id
LEFT JOIN (
  SELECT
    product_id,
    MIN(expiry_date) AS earliest_expiry,
    SUM(remaining) FILTER (WHERE expiry_date < CURRENT_DATE) AS expired_quantity
  FROM batch_stock
  WHERE remaining > 0
  GROUP BY product_id
) e ON e.product_id = p.product_id;
