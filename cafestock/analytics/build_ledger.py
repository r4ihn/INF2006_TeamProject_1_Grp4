#!/usr/bin/env python3
"""
=============================================================================
build_ledger.py - coffee sales -> ingredient-level stock ledger
=============================================================================

INPUT   data/raw/Coffe_sales.csv       3,547 point-of-sale transactions

OUTPUT  data/ingredients.csv           8 stock items the shop actually holds
        data/recipes.csv               bill of materials, drink -> ingredients
        data/stock_movements.csv       the append-only ledger
        data/daily_demand.csv          modelling table, day x ingredient
        data/weekly_demand.csv         modelling table, week x ingredient
        data/validation_report.txt     checks a marker can re-run

WHY INGREDIENT LEVEL
    A cafe does not hold "lattes" in stock. It holds beans, milk and cups.
    Forecasting at drink level also runs into a data problem: four of the
    eight drinks sell nothing on most days (Espresso records zero on 74% of
    days), so a moving average over drink-level demand is mostly noise.

    Rolling the drinks up into ingredients concentrates that demand. Milk is
    consumed by four drinks and beans by six, so both are consumed on 97%+ of
    days and a daily forecast becomes meaningful.

PROVENANCE
    SELL movements are DERIVED from observed sales: every one traces back to
    a real transaction via `sale_id` and `caused_by_drink`. The transaction
    is real; the quantity of milk in a latte is not.

    The recipe quantities, shelf lives, pack sizes and storage locations are
    SYNTHETIC. They are plausible values for a small cafe, not measurements.
    This is the cost of going ingredient level and must be stated plainly in
    the report.

    RECEIVE, SPOILAGE and ADJUST movements are SYNTHETIC, generated by the
    simulation so the ledger balances and never goes negative.

REPRODUCIBILITY
    Fixed seed, no wall-clock reads, no network. Running this twice on the
    same input produces byte-identical output.

    python3 build_ledger.py
=============================================================================
"""

from collections import deque
from pathlib import Path
import hashlib
import numpy as np
import pandas as pd

SEED = 2006
RNG = np.random.default_rng(SEED)

# Paths resolve relative to the repository root, not the working directory,
# so these scripts run identically from anywhere.
ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data/raw/Coffe_sales.csv"
OUT = ROOT / "data"

REPORT = []


def log(msg):
    print(msg)
    REPORT.append(msg)


# =============================================================================
# Reference data
# =============================================================================
# Stock items. shelf_life_days, pack_size, storage_location and unit_cost are
# invented. The wide spread in shelf life is deliberate and is the point of
# going ingredient level: milk at 7 days behaves nothing like cups at 2 years,
# and one forecast has to cope with both.
#
# pack_size matters because suppliers sell whole units. You cannot order
# 1,847 ml of milk; you order two 1-litre bottles.
INGREDIENTS = [
    # name,                unit,   shelf, pack, pack description, location,      cost/unit
    ("Espresso beans",     "g",      90,  1000, "1 kg bag",       "Dry Store 1", 0.042),
    ("Fresh milk",         "ml",      7,  1000, "1 L bottle",     "Chiller",     0.0021),
    ("Drinking chocolate", "g",     365,   750, "750 g tub",      "Dry Store 2", 0.019),
    ("Cocoa powder",       "g",     365,   500, "500 g tub",      "Dry Store 2", 0.024),
    ("Paper cup 8oz",      "unit",  730,    50, "sleeve of 50",   "Dry Store 1", 0.085),
    ("Paper cup 12oz",     "unit",  730,    50, "sleeve of 50",   "Dry Store 1", 0.110),
    ("Cup lid 12oz",       "unit",  730,   100, "box of 100",     "Dry Store 1", 0.045),
    ("Napkin",             "unit",  730,   250, "pack of 250",    "Dry Store 2", 0.008),
]

# Bill of materials: how much of each ingredient one serving consumes.
# Entirely invented. Quantities are integers so the ledger stays exact.
RECIPES = {
    "Espresso":            {"Espresso beans": 9,  "Paper cup 8oz": 1, "Napkin": 1},
    "Americano":           {"Espresso beans": 9,  "Paper cup 12oz": 1, "Cup lid 12oz": 1, "Napkin": 1},
    "Americano with Milk": {"Espresso beans": 9,  "Fresh milk": 60,  "Paper cup 12oz": 1, "Cup lid 12oz": 1, "Napkin": 1},
    "Latte":               {"Espresso beans": 18, "Fresh milk": 220, "Paper cup 12oz": 1, "Cup lid 12oz": 1, "Napkin": 1},
    "Cappuccino":          {"Espresso beans": 18, "Fresh milk": 150, "Paper cup 12oz": 1, "Cup lid 12oz": 1, "Napkin": 1},
    "Cortado":             {"Espresso beans": 18, "Fresh milk": 60,  "Paper cup 8oz": 1,  "Napkin": 1},
    "Hot Chocolate":       {"Drinking chocolate": 25, "Fresh milk": 200, "Paper cup 12oz": 1, "Cup lid 12oz": 1, "Napkin": 1},
    "Cocoa":               {"Cocoa powder": 25, "Fresh milk": 180, "Paper cup 12oz": 1, "Cup lid 12oz": 1, "Napkin": 1},
}

LEAD_TIME_CHILLED = 1     # milk is delivered next day
LEAD_TIME_AMBIENT = 3     # everything else takes three days
REVIEW_DAYS = 1           # stock reviewed daily

# An order must not exceed this share of the item's shelf life in days of
# demand. Without it the policy buys a month of milk and most of it expires.
MAX_COVER_FRACTION = 0.5


# =============================================================================
# 1. Load and clean
# =============================================================================
def load_and_clean() -> pd.DataFrame:
    df = pd.read_csv(RAW)
    log(f"loaded {len(df)} rows, {df.shape[1]} columns")

    df["occurred_at"] = pd.to_datetime(df["Date"] + " " + df["Time"], format="mixed")

    # The source carries six columns all recomputable from the timestamp.
    # Check they agree before discarding them: if the source is internally
    # inconsistent that belongs in the report, not hidden.
    bad_hour = int((df["occurred_at"].dt.hour != df["hour_of_day"]).sum())
    bad_dow = int((df["occurred_at"].dt.dayofweek + 1 != df["Weekdaysort"]).sum())
    log(f"consistency check: hour mismatches={bad_hour}, weekday mismatches={bad_dow}")

    df = df.rename(columns={
        "coffee_name": "drink_name",
        "money": "sale_price",
        "cash_type": "payment_method",
    })[["occurred_at", "drink_name", "sale_price", "payment_method"]]

    assert df.notna().all().all(), "unexpected nulls"
    assert df["payment_method"].isin(["cash", "card"]).all(), "unexpected payment method"
    assert set(df["drink_name"]) <= set(RECIPES), "a drink has no recipe defined"

    df = df.sort_values("occurred_at").reset_index(drop=True)
    df.insert(0, "sale_id", range(1, len(df) + 1))

    log(f"cleaned: {len(df)} transactions, "
        f"{df['occurred_at'].min():%Y-%m-%d} to {df['occurred_at'].max():%Y-%m-%d}")
    return df


# =============================================================================
# 2. Reference tables
# =============================================================================
def build_reference(sales: pd.DataFrame):
    recipe_rows = [
        {"drink_name": d, "ingredient_name": i, "quantity_per_serving": q}
        for d, bom in RECIPES.items() for i, q in bom.items()
    ]
    recipes = pd.DataFrame(recipe_rows)

    # Expected daily consumption per ingredient, from the real sales mix.
    span = (sales["occurred_at"].max() - sales["occurred_at"].min()).days + 1
    counts = sales["drink_name"].value_counts()
    demand = {
        name: sum(counts.get(d, 0) * bom.get(name, 0) for d, bom in RECIPES.items()) / span
        for name, *_ in INGREDIENTS
    }

    rows = []
    for i, (name, unit, shelf, pack, pack_desc, loc, cost) in enumerate(INGREDIENTS, start=1):
        avg = demand[name]
        lead = LEAD_TIME_CHILLED if shelf <= 14 else LEAD_TIME_AMBIENT

        # Static threshold the web app uses for its low-stock flag. The
        # simulation below uses a separate dynamic reorder point.
        reorder_point = int(np.ceil(avg * (REVIEW_DAYS + lead) * 1.5))

        # Order about a week of demand, capped so a perishable item is never
        # bought in a quantity it cannot sell through before expiring.
        cover = min(7, shelf * MAX_COVER_FRACTION)
        packs = max(1, int(np.ceil(avg * cover / pack)))

        rows.append({
            "ingredient_id": i,
            "sku": f"ING-{i:03d}",
            "ingredient_name": name,
            "unit": unit,
            "unit_cost": cost,
            "shelf_life_days": shelf,
            "storage_location": loc,
            "lead_time_days": lead,
            "pack_size": pack,
            "pack_description": pack_desc,
            "reorder_threshold": max(reorder_point, pack // 2),
            "reorder_quantity": packs * pack,
            "avg_daily_demand_derived": round(avg, 2),
        })

    ingredients = pd.DataFrame(rows)
    log(f"built {len(ingredients)} ingredients, {len(recipes)} recipe lines")
    return ingredients, recipes


# =============================================================================
# 3. Ledger simulation
# =============================================================================
def build_ledger(sales, ingredients):
    """Expand every drink sale into ingredient movements, then simulate the
    deliveries, expiry write-offs and stocktakes around them.

    Invariant: on-hand stock never goes negative.
    """
    iid = dict(zip(ingredients["ingredient_name"], ingredients["ingredient_id"]))
    meta = ingredients.set_index("ingredient_id").to_dict("index")
    bom = {d: [(iid[i], q) for i, q in items.items()] for d, items in RECIPES.items()}

    sales = sales.copy()
    sales["date"] = sales["occurred_at"].dt.normalize()
    sales_by_day = {d: g for d, g in sales.groupby("date")}
    calendar = pd.date_range(sales["date"].min(), sales["date"].max(), freq="D")

    movements = []
    batches = {i: [] for i in meta}
    on_order = {i: [] for i in meta}
    recent = {i: deque(maxlen=28) for i in meta}
    batch_seq = 0

    def on_hand(i):
        return sum(b["qty"] for b in batches[i])

    def add(ts, i, mtype, qty, source, batch_id=None, expiry=None,
            sale_id=None, drink=None, price=None, payment=None, reason=None):
        movements.append({
            "occurred_at": ts,
            "ingredient_id": i,
            "movement_type": mtype,
            "quantity": qty,                 # signed: + adds stock, - removes
            "batch_id": batch_id,
            "expiry_date": expiry,
            "storage_location": meta[i]["storage_location"],
            "sale_id": sale_id,
            "caused_by_drink": drink,
            "sale_price": price,
            "payment_method": payment,
            "reason": reason,
            "source": source,
        })

    def receive(day, i, qty, ts, reason):
        nonlocal batch_seq
        batch_seq += 1
        bid = f"B{batch_seq:06d}"
        expiry = day + pd.Timedelta(days=meta[i]["shelf_life_days"])
        batches[i].append({"batch_id": bid, "qty": qty, "expiry": expiry})
        add(ts, i, "RECEIVE", qty, "synthetic", bid, expiry, reason=reason)

    # --- opening stock -------------------------------------------------------
    open_day = calendar[0] - pd.Timedelta(days=1)
    for i, m in meta.items():
        receive(open_day, i, m["reorder_threshold"] + m["reorder_quantity"],
                open_day + pd.Timedelta(hours=8), "Opening stock")

    # --- day by day ----------------------------------------------------------
    for day in calendar:
        # 3a. deliveries land before opening
        for i in meta:
            for _, qty in [o for o in on_order[i] if o[0] == day]:
                receive(day, i, qty, day + pd.Timedelta(hours=7), "Supplier delivery")
            on_order[i] = [o for o in on_order[i] if o[0] != day]

        # 3b. expiry write-off. This is where the short shelf life on milk
        # bites, which is the whole reason for modelling ingredients.
        for i in meta:
            for b in batches[i]:
                if b["expiry"] < day and b["qty"] > 0:
                    add(day + pd.Timedelta(hours=7, minutes=30), i, "SPOILAGE",
                        -b["qty"], "synthetic", b["batch_id"], b["expiry"],
                        reason="Expired, written off")
                    b["qty"] = 0
            batches[i] = [b for b in batches[i] if b["qty"] > 0]

        # 3c. real sales, expanded through the recipe, consumed first-expiry-first-out
        if day in sales_by_day:
            for row in sales_by_day[day].itertuples():
                for i, need in bom[row.drink_name]:
                    # Top up first if the line cannot be covered. A real cafe
                    # sends someone to the cash-and-carry rather than turning
                    # the customer away.
                    if on_hand(i) < need:
                        pack = meta[i]["pack_size"]
                        short = need - on_hand(i)
                        receive(day, i, int(np.ceil(short / pack)) * pack,
                                row.occurred_at - pd.Timedelta(minutes=1),
                                "Emergency top-up, stock ran out")

                    remaining = need
                    batches[i].sort(key=lambda b: b["expiry"])
                    while remaining > 0:
                        b = batches[i][0]
                        take = min(remaining, b["qty"])
                        add(row.occurred_at, i, "SELL", -take, "derived",
                            b["batch_id"], b["expiry"], row.sale_id,
                            row.drink_name, row.sale_price, row.payment_method,
                            reason="Counter sale")
                        b["qty"] -= take
                        remaining -= take
                        if b["qty"] == 0:
                            batches[i].pop(0)

        # 3d. record today's consumption for the trailing window
        used = {i: 0 for i in meta}
        if day in sales_by_day:
            for row in sales_by_day[day].itertuples():
                for i, need in bom[row.drink_name]:
                    used[i] += need
        for i in meta:
            recent[i].append(used[i])

        # 3e. daily stock review
        #
        # The reorder point is recomputed from the trailing 28 days rather
        # than fixed from the whole-period average. Demand roughly doubles
        # across the year, so a static threshold either runs out in the busy
        # months or over-buys in the quiet ones.
        for i, m in meta.items():
            hist = list(recent[i])
            avg = float(np.mean(hist)) if hist else m["avg_daily_demand_derived"]
            sd = float(np.std(hist)) if len(hist) > 1 else avg * 0.5

            reorder_point = avg * (REVIEW_DAYS + m["lead_time_days"]) + 3 * sd

            cover = min(7, m["shelf_life_days"] * MAX_COVER_FRACTION)
            pack = m["pack_size"]
            packs = max(1, int(np.ceil(avg * cover / pack)))

            position = on_hand(i) + sum(q for _, q in on_order[i])
            if position <= reorder_point:
                jitter = int(RNG.integers(0, 2)) if packs > 2 else 0
                on_order[i].append(
                    (day + pd.Timedelta(days=m["lead_time_days"]), (packs + jitter) * pack))

        # 3f. occasional stocktake correction
        for i in meta:
            if RNG.random() < 0.02 and on_hand(i) > meta[i]["pack_size"]:
                batches[i].sort(key=lambda b: b["expiry"])
                b = batches[i][0]
                delta = -int(np.ceil(b["qty"] * RNG.uniform(0.01, 0.03)))
                if b["qty"] + delta > 0:
                    b["qty"] += delta
                    add(day + pd.Timedelta(hours=21), i, "ADJUST", delta,
                        "synthetic", b["batch_id"], b["expiry"],
                        reason="Stocktake correction")

    ledger = pd.DataFrame(movements).sort_values(
        ["occurred_at", "ingredient_id"], kind="stable").reset_index(drop=True)
    ledger.insert(0, "movement_id", range(1, len(ledger) + 1))

    log(f"\nledger: {len(ledger)} movements")
    log(f"  by type:\n{ledger['movement_type'].value_counts().to_string()}")
    log(f"  by source:\n{ledger['source'].value_counts().to_string()}")
    return ledger


# =============================================================================
# 4. Modelling tables
# =============================================================================
def build_demand(ledger, ingredients):
    sells = ledger[ledger["movement_type"] == "SELL"].copy()
    sells["date"] = sells["occurred_at"].dt.normalize()
    sells["units"] = -sells["quantity"]

    calendar = pd.date_range(sells["date"].min(), sells["date"].max(), freq="D")
    grid = pd.MultiIndex.from_product(
        [calendar, ingredients["ingredient_id"]], names=["date", "ingredient_id"])

    # Zero-consumption days must appear as explicit zeros, or every moving
    # average is computed over trading days only and comes out too high.
    daily = (sells.groupby(["date", "ingredient_id"])["units"].sum()
             .reindex(grid, fill_value=0).reset_index())
    daily["weekday"] = daily["date"].dt.day_name()
    daily["is_weekend"] = daily["date"].dt.dayofweek >= 5
    daily["month"] = daily["date"].dt.month
    daily = daily.merge(
        ingredients[["ingredient_id", "ingredient_name", "unit"]], on="ingredient_id")

    weekly = (daily.set_index("date").groupby("ingredient_id")["units"]
              .resample("W-MON", label="left", closed="left").sum()
              .reset_index().rename(columns={"date": "week_starting"}))
    weekly = weekly.merge(
        ingredients[["ingredient_id", "ingredient_name", "unit"]], on="ingredient_id")

    log(f"daily demand: {len(daily)} rows "
        f"({daily['date'].nunique()} days x {daily['ingredient_id'].nunique()} ingredients)")
    log(f"weekly demand: {len(weekly)} rows")

    zero = daily.groupby("ingredient_name")["units"].apply(lambda s: (s == 0).mean())
    log("\nshare of days with zero consumption (lower is better for forecasting):")
    for name, v in zero.sort_values().items():
        log(f"  {name:<22} {v:>6.0%}")
    return daily, weekly


# =============================================================================
# 5. Validation
# =============================================================================
def validate(ledger, ingredients, sales):
    log("\n--- validation ---")
    ok = True
    m = ingredients.set_index("ingredient_id")

    log("closing stock (SUM of all movements):")
    for i, v in ledger.groupby("ingredient_id")["quantity"].sum().items():
        log(f"  {m.loc[i,'ingredient_name']:<22} {int(v):>8} {m.loc[i,'unit']}")

    running_min = (ledger.groupby("ingredient_id")["quantity"].cumsum()
                   .groupby(ledger["ingredient_id"]).min())
    if (running_min < 0).any():
        log(f"FAIL: running balance went negative: {running_min[running_min < 0].to_dict()}")
        ok = False
    else:
        log("PASS: running balance stays non-negative throughout")

    expected = int(sum(int((sales["drink_name"] == d).sum()) * sum(b.values())
                       for d, b in RECIPES.items()))
    actual = int(-ledger.loc[ledger.movement_type == "SELL", "quantity"].sum())
    log(f"consumed units: {actual} (recipe expansion of {len(sales)} sales expects {expected})")
    if actual != expected:
        log("FAIL: consumption does not reconcile to the recipes")
        ok = False
    else:
        log("PASS: every sale expanded through its recipe exactly once")

    traced = ledger.loc[ledger.movement_type == "SELL", "sale_id"].nunique()
    log(f"distinct sales traceable in the ledger: {traced} of {len(sales)}")
    if traced != len(sales):
        log("FAIL: some sales are missing from the ledger")
        ok = False
    else:
        log("PASS: every source transaction is traceable via sale_id")

    emerg = int((ledger["reason"] == "Emergency top-up, stock ran out").sum())
    log(f"\nstockout events requiring an emergency top-up: {emerg}")

    log("spoilage by ingredient (expired as % of consumed):")
    used = -ledger[ledger.movement_type == "SELL"].groupby("ingredient_id")["quantity"].sum()
    spoiled = -ledger[ledger.movement_type == "SPOILAGE"].groupby("ingredient_id")["quantity"].sum()
    for i in m.index:
        u, s = int(used.get(i, 0)), int(spoiled.get(i, 0))
        log(f"  {m.loc[i,'ingredient_name']:<22} {s/u if u else 0:>6.1%}  "
            f"({s} of {u} {m.loc[i,'unit']})")

    log(f"\nresult: {'ALL CHECKS PASSED' if ok else 'CHECKS FAILED'}")
    return ok


# =============================================================================
def main():
    OUT.mkdir(exist_ok=True)
    (OUT / "raw").mkdir(exist_ok=True)

    sales = load_and_clean()
    ingredients, recipes = build_reference(sales)
    ledger = build_ledger(sales, ingredients)
    daily, weekly = build_demand(ledger, ingredients)
    validate(ledger, ingredients, sales)

    ingredients.to_csv(OUT / "ingredients.csv", index=False)
    recipes.to_csv(OUT / "recipes.csv", index=False)
    ledger.to_csv(OUT / "stock_movements.csv", index=False)
    daily.to_csv(OUT / "daily_demand.csv", index=False)
    weekly.to_csv(OUT / "weekly_demand.csv", index=False)

    log("\n--- output checksums (sha256, first 16 chars) ---")
    for f in ["ingredients.csv", "recipes.csv", "stock_movements.csv",
              "daily_demand.csv", "weekly_demand.csv"]:
        log(f"  {f:<24} {hashlib.sha256((OUT / f).read_bytes()).hexdigest()[:16]}")

    (OUT / "validation_report.txt").write_text("\n".join(REPORT) + "\n")
    print(f"\nwrote 6 files to {OUT}/")


if __name__ == "__main__":
    main()
